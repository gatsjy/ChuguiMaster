from typing import Dict, Any

class MessageGenerator:
    """
    하객 정보(이름, 관계, 참석여부 등)에 기반하여 톤앤매너별 감사 메시지를 자동 생성하는 모듈
    """
    
    TEMPLATES = {
        '직장': {
            '참석': "{name} 님, 바쁘신 와중에도 저희 결혼식에 참석하여 자리를 빛내주셔서 진심으로 감사드립니다. 따뜻한 축하 말씀 가슴 깊이 새기며, 행복하게 잘 살겠습니다.",
            '불참(송금)': "{name} 님, 전해주신 소중한 축의금과 따뜻한 축하 마음에 깊이 감사드립니다. 직접 모시지 못해 아쉽지만, 조만간 감사한 마음을 담아 인사드리겠습니다."
        },
        '친척': {
            '참석': "{name}님, 저희 결혼식에 오셔서 따뜻하게 축복해 주셔서 정말 감사합니다. 귀한 발걸음해 주신 덕분에 더욱 뜻깊은 날이 되었습니다. 항상 건강하시고 행복하세요!",
            '불참(송금)': "{name}님, 마음 담아 보내주신 소중한 축의금에 진심으로 감사드립니다. 직접 뵙지 못해 아쉽지만, 조만간 찾아뵙고 정식으로 인사드리겠습니다."
        },
        '대학': {
            '참석': "{name}야! 바쁜 와중에 멀리서 결혼식 찾아와주고 축하해 줘서 진짜 고마워! 덕분에 힘이 많이 됐다. 신혼여행 다녀와서 조만간 맛있는 거 사줄게!",
            '불참(송금)': "{name}야, 사정 때문에 오지 못했지만 마음 담아 보내준 축의금 정말 고마워! 조만간 만나서 맛있는 거 먹으며 이야기 나누자!"
        },
        '고교/초중': {
            '참석': "{name}야! 오늘 내 결혼식 와줘서 너무 반가웠고 진짜 고마워! 와준 덕분에 정말 행복했어. 조만간 얼굴 보고 제대로 쏘겠다!",
            '불참(송금)': "{name}야! 사정으로 못 와서 아쉬웠지만 축하해 준 마음 잘 받았어, 너무 고마워! 조만간 밥 한 끼 사줄게!"
        },
        '지인/기타': {
            '참석': "{name} 님, 저희 결혼식에 참석해 주셔서 진심으로 감사드립니다. 보내주신 축복에 보답하며 예쁘고 행복하게 살아가겠습니다. 늘 건강하세요!",
            '불참(송금)': "{name} 님, 소중한 축하와 축의를 전해 주셔서 깊이 감사드립니다. 따뜻한 마음 항상 간직하겠습니다."
        }
    }

    @classmethod
    def generate(cls, guest: Dict[str, Any]) -> str:
        """
        하객 정보 dict를 받아 정교한 감사 메시지 생성
        """
        name = guest.get('name', '손님')
        relation = guest.get('relation', '지인/기타')
        attended_status = guest.get('attended', '참석')
        
        # 기본 템플릿 매핑
        rel_templates = cls.TEMPLATES.get(relation, cls.TEMPLATES['지인/기타'])
        template = rel_templates.get(attended_status, rel_templates['참석'])
        
        return template.format(name=name)
